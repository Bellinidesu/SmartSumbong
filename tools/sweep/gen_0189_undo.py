#!/usr/bin/env python3
"""Writes supabase/drafts/0189_undo.sql from a database that does NOT have 0189 yet (the throwaway copy built from the migrations, whose policies
equal live: compare with `python gen_0189_undo.py --check-live`). The undo restores every policy 0189 rewrites word for word (ALTER POLICY ... USING
the text pg_policies holds today) and drops the 7 helpers. usage: python gen_0189_undo.py [DB]"""
import re, sys
from common import *

POLICIES = re.findall(r"alter policy (\w+) on public\.(\w+)", read(ROOT / "supabase/drafts/0189_case_rule_at_scale.sql"))
HELPERS = re.findall(r"create or replace function public\.(_my_\w+)\(\)", read(ROOT / "supabase/drafts/0189_case_rule_at_scale.sql"))


def main():
    if "--check-live" in sys.argv:
        names = ",".join(f"'{t}.{p}'" for p, t in POLICIES)
        q = f"select tablename || '.' || policyname as p, md5(coalesce(qual, '')) as h from pg_policies where schemaname = 'public' and tablename || '.' || policyname in ({names}) order by 1"
        lv = {r["p"]: r["h"] for r in live(q)}
        lc = dict(r for r in psql(q, db=sys.argv[2] if len(sys.argv) > 2 else "k04_base") if len(r) == 2)   # both sides with their default search_path (the text form then matches)
        same = [k for k in lc if lv.get(k) == lc[k]]
        print(f"live vs local: {len(same)} of {len(lc)} policies identical; differ: {[k for k in lc if lv.get(k) != lc[k]]}")
        return
    db = sys.argv[1] if len(sys.argv) > 1 else "k04_base"
    if psql("select count(*) from pg_proc where proname = '_my_scoped_case_ids'", db=db)[0][0] != "0":
        raise SystemExit(f"{db} already has 0189: build the undo from a database without it")
    out = ["-- 0189 UNDO: puts back exactly what was there before 0189 (generated by tools/sweep/gen_0189_undo.py from a copy built from the",
           "-- migrations 0001-0188, whose policy texts equal live; checked with --check-live). Run it as one transaction, like 0189.",
           "-- Plain language: every policy 0189 rewrote is set back to its old condition, word for word (the per-row case functions it used still",
           "-- exist: 0189 never touched them), then the 7 helpers 0189 added are dropped. Who sees what does not change in either direction.",
           "", "set search_path = public, extensions;", "set local lock_timeout = '5s';", ""]
    for pol, tbl in POLICIES:
        qual = psqlj(f"select qual from pg_policies where schemaname = 'public' and tablename = '{tbl}' and policyname = '{pol}'", db=db,
                     setup="set search_path = ''; ")[0]["qual"]   # empty search_path: the text keeps public. on every name
        out.append(f"alter policy {pol} on public.{tbl} using ({qual});")
    out.append("")
    for h in reversed(HELPERS):
        out.append(f"drop function if exists public.{h}();")
    (ROOT / "supabase/drafts/0189_undo.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote supabase/drafts/0189_undo.sql: {len(POLICIES)} policies, {len(HELPERS)} helpers")


if __name__ == "__main__":
    main()
