#!/usr/bin/env python3
"""Class A generator: a pgTAP-style skeleton for every API-callable function that no test names (out/untested_functions.json). Per function: it exists,
signed-out and signed-in rights equal supabase/grants.txt, a SECURITY DEFINER function pins its search_path, and a function that reads auth.uid() refuses a
signed-out caller. This is a regression guard (it passes today); the behaviour checks per function are the human's. Writes supabase/drafts/tests/skeleton_untested_functions.test.sql
usage: python fix/gen_test_skeleton.py"""
import json
from fixlib import *


def main():
    un = json.loads(read(OUT / "untested_functions.json"))["api_callable"]
    G = grants()["fn"]
    rows = []
    for n in un:
        r = psqlj(f"select p.oid::regprocedure::text sig, p.prosecdef sd, (p.proconfig::text ~ 'search_path') sp, (p.prosrc ~ 'auth\.uid\(\)') uid, p.prorettype::regtype::text ret from pg_proc p where p.proname = '{n}' and p.pronamespace = 'public'::regnamespace")
        if not r: continue
        a, u = G.get(n, ("-", "-"))
        for x in r: rows.append((x["sig"], a == "call", u == "call", x["sd"], x["sp"], x["uid"], x["ret"] == "trigger"))
    vals = ",\n    ".join(f"('{s}', {str(a).lower()}, {str(u).lower()}, {str(sd).lower()}, {str(sp).lower()}, {str(uid).lower()})" for s, a, u, sd, sp, uid, tr in rows)
    sql = f"""-- Skeleton checks for {len(rows)} API-callable functions that no test names (generated by tools/sweep/fix/gen_test_skeleton.py from out/untested_functions.json
-- and supabase/grants.txt). A regression guard: rights as filed, search_path pinned, signed-out refused. Behaviour checks per function are still to be written.
-- Rolled back like every script in supabase/tests.
do $sweep$
declare
  v_log text := 'setup ok'; r record; bad text;
begin
  for r in select * from (values
    {vals}
  ) as t(sig, anon_call, auth_call, secdef, pinned, reads_uid)
  loop
    begin
      perform r.sig::regprocedure;
      if has_function_privilege('anon', r.sig::regprocedure, 'execute') <> r.anon_call then raise exception 'anon right differs from grants.txt'; end if;
      if has_function_privilege('authenticated', r.sig::regprocedure, 'execute') <> r.auth_call then raise exception 'authenticated right differs from grants.txt'; end if;
      if r.secdef and not r.pinned then raise exception 'SECURITY DEFINER without a pinned search_path'; end if;
      if r.reads_uid and r.anon_call then raise exception 'reads auth.uid() but a signed-out caller may run it'; end if;
    exception when others then bad := coalesce(bad || E'\n', '') || 'FAIL ' || r.sig || ': ' || sqlerrm;
    end;
  end loop;
  v_log := v_log || E'\n' || coalesce(bad, 'ok  all {len(rows)} functions: exist, rights match grants.txt, search_path pinned, signed-out refused where auth.uid() is read');
  raise exception E'SWEEP-ROLLBACK\n%', v_log;
end $sweep$;
"""
    out = DRAFTS / "tests" / "skeleton_untested_functions.test.sql"
    out.write_text(sql, encoding="utf-8")
    scratch()
    o, f = results(run_sql(out))
    print(f"SKELETON supabase/drafts/tests/skeleton_untested_functions.test.sql: {len(rows)} functions; on the migrations-built schema: {len(o)} ok, {len(f)} FAIL")
    for l in f[:6]: print("   !", l[:170])


if __name__ == "__main__":
    main()
