#!/usr/bin/env python3
"""Class A generator (ledger T-04, T-05): pgTAP-style tests, in the repo's rolled-back style, for every API-callable function and every RLS table that no test names
(out/untested_functions.json, from standards.py). Writes supabase/tests/NN_*.sql (they must PASS on the migrations-built schema: CI's database job runs them).
Per function: it exists; the signed-out and signed-in execute rights equal supabase/grants.txt; a SECURITY DEFINER function pins its search_path; a function that reads
auth.uid() is not executable by anon; and, where the dynamic prober (probe.py) saw every non-admin refused in every state, a signed-in resident calling it with
placeholder arguments is refused (42501 or an 'Only ...' message). Per table: it exists, row level security is on, the rights equal grants.txt, it has a policy when
signed-in callers may select, a signed-in stranger can read it without an error, and a signed-out caller is refused when anon has no select.
usage: SWEEP_PORT=.. python fix/gen_skeleton_tests.py [first_number]   (default 72)"""
import json, re, sys
from fixlib import *

PER_FILE = 12
PH = {"uuid": "'00000000-0000-4000-8000-000000000001'::uuid", "text": "'x'", "character varying": "'x'", "boolean": "false", "integer": "1", "bigint": "1", "smallint": "1",
      "double precision": "1.0", "jsonb": "'{}'::jsonb", "json": "'{}'::json", "timestamp with time zone": "now()", "date": "current_date", "uuid[]": "array[]::uuid[]", "text[]": "array[]::text[]"}


def call_sql(r, G):
    """a placeholder call for the function, or None when an argument type has no placeholder"""
    names, types, nd = r["names"] or [], r["types"] or [], r["nd"] or 0
    args = []
    for nm, ty in list(zip(names, types))[: len(names) - nd]:
        if ty in PH: args.append(PH[ty])
        else: return None
    return f"select public.{r['proname']}({', '.join(args)})"


def main():
    first = int(sys.argv[1]) if len(sys.argv) > 1 else 72
    un = json.loads(read(OUT / "untested_functions.json"))
    G = grants()
    funcs = un["api_callable"]
    rows = []
    for n in funcs:
        for x in psqlj(f"select p.proname, p.oid::regprocedure::text sig, p.prosecdef sd, (p.proconfig::text ~ 'search_path') sp, (p.prosrc ~ 'auth\\.uid\\(\\)') uid, p.prorettype::regtype::text ret, "
                       f"p.proargnames names, (select array_agg(format_type(t, null)) from unnest(p.proargtypes) t) types, p.pronargdefaults nd from pg_proc p where p.proname = '{n}' and p.pronamespace = 'public'::regnamespace"):
            a, u = G["fn"].get(n, ("-", "-"))
            x.update(anon=a == "call", auth=u == "call"); rows.append(x)
    # who is refused in every probe (non-admin residents), from the prober's results on the small database
    denied = set()
    pj = OUT / "probe_roles.json"
    if pj.exists():
        for fn, m in json.loads(read(pj)).items():
            if m.get("res1") == "denied" and m.get("res2") == "denied" and m.get("tan1") == "denied": denied.add(fn)
    files = []
    for i in range(0, len(rows), PER_FILE):
        chunk = rows[i:i + PER_FILE]
        items = []
        for x in chunk:
            c = call_sql(x, G) if x["proname"] in denied and x["ret"] != "trigger" else None
            items.append((x["sig"], str(x["anon"]).lower(), str(x["auth"]).lower(), str(x["sd"]).lower(), str(x["sp"]).lower(), str(x["uid"]).lower(), c))
        vals = ",\n    ".join("('" + s + "', " + a + ", " + u + ", " + sd + ", " + sp + ", " + uid + ", " + ("$c$" + c + "$c$" if c else "null") + ")" for s, a, u, sd, sp, uid, c in items)
        files.append((chunk, vals))
    num = first
    out_names = []
    for k, (chunk, vals) in enumerate(files):
        names = ", ".join(x["proname"] for x in chunk)
        sql = f"""-- {num}_untested_functions_{chr(97 + k)}.sql: a first check for {len(chunk)} API-callable functions that no other script names (generated by tools/sweep/fix/gen_skeleton_tests.py from the sweep's
-- coverage map and supabase/grants.txt): {names}.
-- Each: it exists; the signed-out and signed-in execute rights are the ones on file (supabase/grants.txt); a SECURITY DEFINER function pins its search_path; a function that
-- reads auth.uid() is not executable signed out; and where the sweep's prober saw a signed-in resident refused in every state, that refusal holds with placeholder arguments.
-- The behaviour of each function is still to be written. Rolled back like every script in supabase/tests.
do $sweep$
declare
  v_log text := 'setup ok'; r record; bad text := ''; v_res uuid := gen_random_uuid(); n_refused int := 0;
begin
  insert into auth.users (instance_id, id, aud, role, email, raw_user_meta_data, created_at, updated_at)
  values ('00000000-0000-0000-0000-000000000000', v_res, 'authenticated', 'authenticated', public.auth_email_for('+639999998{k:03d}'),
          jsonb_build_object('full_name', 'Skeleton, Resident', 'mobile_number', '+639999998{k:03d}', 'role', 'resident', 'id_type', 'barangay_id',
                             'id_image_url', 'https://res.cloudinary.com/nwb2kryl/image/upload/v1/ids/' || gen_random_uuid() || '.jpg',
                             'selfie_url', 'https://res.cloudinary.com/nwb2kryl/image/upload/v1/selfies/' || gen_random_uuid() || '.jpg'), now(), now());
  update public.users set verification_status = 'verified', verified_at = now() where id = v_res;
  for r in select * from (values
    {vals}
  ) as t(sig, anon_call, auth_call, secdef, pinned, reads_uid, placeholder)
  loop
    begin
      perform r.sig::regprocedure;
      if has_function_privilege('anon', r.sig::regprocedure, 'execute') <> r.anon_call then raise exception 'anon right differs from grants.txt'; end if;
      if has_function_privilege('authenticated', r.sig::regprocedure, 'execute') <> r.auth_call then raise exception 'authenticated right differs from grants.txt'; end if;
      if r.secdef and not r.pinned then raise exception 'SECURITY DEFINER without a pinned search_path'; end if;
      if r.reads_uid and r.anon_call then raise exception 'reads auth.uid() but a signed-out caller may run it'; end if;
      if r.placeholder is not null and r.auth_call then
        perform set_config('request.jwt.claim.sub', v_res::text, true);
        execute 'set local role authenticated';
        begin
          execute r.placeholder;
          execute 'reset role';
          raise exception 'a signed-in resident was not refused';
        exception when others then
          execute 'reset role';
          if sqlerrm = 'a signed-in resident was not refused' then raise; end if;
          if sqlstate <> '42501' and sqlerrm !~* '^(only|this account|not allowed|you may|no access|administrators|permission)' then raise exception 'refused with an unexpected error: %', left(sqlerrm, 80); end if;
          n_refused := n_refused + 1;
        end;
      end if;
    exception when others then bad := bad || E'\\n' || 'FAIL ' || r.sig || ': ' || sqlerrm;
    end;
  end loop;
  v_log := v_log || case when bad = '' then format(E'\\nok  all {len(chunk)} functions: exist, rights match grants.txt, search_path pinned, signed-out refused where auth.uid() is read; %s resident refusals held', n_refused) else bad end;
  raise exception E'SWEEP-ROLLBACK\\n%', v_log;
end $sweep$;
"""
        p = ROOT / "supabase" / "tests" / f"{num}_untested_functions_{chr(97 + k)}.sql"
        wt(p, sql); out_names.append(p); num += 1
    # tables
    tabs = un["tables"]
    trows = []
    for t in tabs:
        a, u = G["table"].get(t, ("-", "-"))
        trows.append((t, a, u))
    vals = ",\n    ".join(f"('{t}', '{a}', '{u}')" for t, a, u in trows)
    sql = f"""-- {num}_untested_tables.sql: a first check for {len(tabs)} tables with row level security policies that no other script names (generated by tools/sweep/fix/gen_skeleton_tests.py):
-- {', '.join(tabs)}.
-- Each: it exists; row level security is on; the signed-out and signed-in rights are the ones on file (supabase/grants.txt); it has a policy when signed-in callers may select;
-- a signed-in stranger (a resident with no connection to any case) reads it without an error; a signed-out caller is refused where anon has no select.
-- The rows each rung may read are still to be written per table. Rolled back like every script in supabase/tests.
do $sweep$
declare
  v_log text := 'setup ok'; r record; bad text := ''; v_res uuid := gen_random_uuid(); n integer; ok_ int;
begin
  insert into auth.users (instance_id, id, aud, role, email, raw_user_meta_data, created_at, updated_at)
  values ('00000000-0000-0000-0000-000000000000', v_res, 'authenticated', 'authenticated', public.auth_email_for('+639999998900'),
          jsonb_build_object('full_name', 'Skeleton, Stranger', 'mobile_number', '+639999998900', 'role', 'resident', 'id_type', 'barangay_id',
                             'id_image_url', 'https://res.cloudinary.com/nwb2kryl/image/upload/v1/ids/' || gen_random_uuid() || '.jpg',
                             'selfie_url', 'https://res.cloudinary.com/nwb2kryl/image/upload/v1/selfies/' || gen_random_uuid() || '.jpg'), now(), now());
  update public.users set verification_status = 'verified', verified_at = now() where id = v_res;
  for r in select * from (values
    {vals}
  ) as t(tbl, anon_rights, auth_rights)
  loop
    begin
      perform ('public.' || r.tbl)::regclass;
      if not (select c.relrowsecurity from pg_class c where c.oid = ('public.' || r.tbl)::regclass) then raise exception 'row level security is off'; end if;
      if has_table_privilege('anon', 'public.' || r.tbl, 'select') <> (r.anon_rights like '%select%') then raise exception 'anon select right differs from grants.txt'; end if;
      if has_table_privilege('authenticated', 'public.' || r.tbl, 'select') <> (r.auth_rights like '%select%') then raise exception 'authenticated select right differs from grants.txt'; end if;
      if r.auth_rights like '%select%' and not exists (select 1 from pg_policies p where p.schemaname = 'public' and p.tablename = r.tbl) then raise exception 'readable signed in, but no policy'; end if;
      if r.auth_rights like '%select%' then
        perform set_config('request.jwt.claim.sub', v_res::text, true);
        execute 'set local role authenticated';
        begin execute format('select count(*) from public.%I', r.tbl) into n; exception when others then execute 'reset role'; raise exception 'a signed-in stranger cannot read it: %', left(sqlerrm, 80); end;
        execute 'reset role';
      end if;
      if r.anon_rights not like '%select%' then
        execute 'set local role anon';
        begin execute format('select count(*) from public.%I', r.tbl) into n; execute 'reset role'; raise exception 'a signed-out caller can read it';
        exception when insufficient_privilege then execute 'reset role'; end;
      end if;
    exception when others then execute 'reset role'; bad := bad || E'\\n' || 'FAIL ' || r.tbl || ': ' || sqlerrm;
    end;
  end loop;
  v_log := v_log || case when bad = '' then E'\\nok  all {len(tabs)} tables: row level security on, rights match grants.txt, a policy where readable, a stranger reads without error, signed out refused' else bad end;
  raise exception E'SWEEP-ROLLBACK\\n%', v_log;
end $sweep$;
"""
    p = ROOT / "supabase" / "tests" / f"{num}_untested_tables.sql"
    wt(p, sql); out_names.append(p)
    print(f"SKELETONS {len(rows)} functions in {len(files)} files ({PER_FILE} each), {len(tabs)} tables in 1 file: " + ", ".join(p.name for p in out_names))
    print(f"  resident-refusal checks generated for {sum(1 for f in files for _ in [0])} files: functions with a placeholder call: {sum(1 for x in rows if x['proname'] in denied and x['ret'] != 'trigger' and call_sql(x, G))}")
    return out_names


if __name__ == "__main__":
    names = main()
    scratch()
    bad = 0
    for p in names:
        o, f = results(run_sql(p))
        print(f"  {p.name}: {len(o)} ok, {len(f)} FAIL")
        for l in f[:6]: print("     !", l[:170]); bad += 1
    sys.exit(1 if bad else 0)
