#!/usr/bin/env python3
"""Step 5/7/8: regenerates the AUTO section of docs/sweep/GAP_LEDGER.md from the tools' output (out/*.json). Everything outside the markers
is the team's: append your own rows to the table under 'Business gaps' (plain markdown, one row per line). Classifies every row
A (a script can generate the fix), B (needs one human decision, then scripted), C (changes the look: waits for Rose).
Prints severity and class counts, and writes out/ledger_counts.json."""
import json, re
from collections import Counter
from common import *

LEDGER = ROOT / "docs" / "sweep" / "GAP_LEDGER.md"
B, E = "<!-- AUTO:BEGIN (regenerated by tools/sweep/ledger.py; edit below the END marker, not here) -->", "<!-- AUTO:END -->"
# kind -> (class, generator or options file)
KIND = {"reopen-flow": ("B", "options/K-01-reopen-flow.md (button = C)"), "notice-scope": ("A", "fix/gen_notice_report_id.py"), "notice-report-id": ("A", "fix/gen_notice_report_id.py"),
        "missing-label": ("A", "fix/gen_notif_labels.py (not built)"), "dead-kind": ("B", "options/B-dead-code.md"), "write-only-table": ("B", "options/B-dead-code.md"),
        "read-never-written": ("B", "options/B-dead-code.md"), "log-instead-of-swallow": ("A", "fix/gen_log_swallowed.py"), "unreachable-state": ("B", "options/B-state-machine.md"),
        "dead-end": ("B", "options/B-state-machine.md"), "no-decision-path": ("B", "options/B-request-decision.md"), "no-answer-notice": ("B", "options/B-request-decision.md"),
        "no-deny-path": ("B", "options/B-request-decision.md"), "uncalled-request": ("B", "options/B-request-decision.md"), "role-asymmetry": ("B", "options/B-role-symmetry.md"),
        "author-admitted": ("B", "check still true, then drop or schedule"), "doc-drift": ("A", "fix/gen_docs.py (not built; edit the doc)"), "baseline-stale": ("A", "bash supabase/baseline/build.sh"),
        "missing-index": ("A", "fix/gen_indexes.py"), "revoke-unused": ("A", "fix/gen_revoke_unused.py"), "untested": ("A", "fix/gen_test_skeleton.py"), "perf": ("B", "options/K-04-f09-case-rule.md")}
KNOWN = [
    ("K-01", "request_reopen (0037) + reopen_report", "Reopen flow is broken end to end: the notice goes to EVERY active admin with no report_id (no Review button; reaches admins who cannot see the case since 0175), no portal action calls reopen_report(), closed cases cannot be reopened (admin_set_status refuses closed/archived), the resident gets no answer or decline.", "high", "open", "reopen-flow"),
    ("K-02", "F07 docs/BACKEND_SWEEP_2026-11.md", "password-otp code fix (F07) deployed 20 Nov.", "info", "done", None),
    ("K-03", "F08 docs/BACKEND_SWEEP_2026-11.md", "Cloudinary secrets are missing from the Edge Function secrets (Ace's to set), so sign-upload/media-cleanup cannot talk to Cloudinary.", "high", "open (Ace)", None),
    ("K-04", "F09 docs/BACKEND_SWEEP_2026-11.md", "Kagawad/staff count(*) over reports takes 7-14 s at 20,000 cases: the case rule (_user_sees_case) runs per row inside the policy. Core rule; options file proposed.", "high", "open", "perf"),
    ("K-05", "branch notices-backend", "Barangay notices backend drafted by an agent on branch notices-backend; paused for the UI freeze.", "info", "paused", None),
]


def rows():
    out = []
    for k in KNOWN:
        cl = KIND.get(k[5], ("B", "Ace")) if k[5] else ("B", "Ace/none")
        out.append((k[0], k[1], k[2], k[3], k[4], cl[0], cl[1]))
    det = json.loads(read(OUT / "detectors.json")) if (OUT / "detectors.json").exists() else {}
    seen = set()
    for d, lst in det.items():
        n = 0
        for r in lst:
            if d == "D4" and n >= 25: continue
            key = (r["fix"], re.sub(r"\d+", "", r["gap"])[:70])
            if key in seen: continue
            seen.add(key); n += 1
            cl = KIND.get(r["fix"], ("B", "-"))
            out.append((r["id"], f"{d} {r['src']}".strip(), r["gap"], r["sev"], "open", cl[0], cl[1]))
    pm = json.loads(read(OUT / "pagemap.json")) if (OUT / "pagemap.json").exists() else None
    if pm:
        v = pm["violations"]
        dw = [x for x in v.get("direct_table_write", [])]
        if dw: out.append(("P-01", "pagemap.py", f"{len(dw)} places in the portal write a table directly instead of through a function (e.g. {dw[0]}); with grants and policies as the only guard.", "low", "open", "A", "fix/gen_revoke_unused.py (after a human check of each)"))
        for key, sev in (("rpc_called_but_missing", "high"), ("rpc_called_but_not_granted", "high"), ("no_csrf_post_handler", "medium"), ("api_callable_rpc_never_called_anywhere", "low")):
            if v.get(key): out.append((f"P-{len(out):02d}", "pagemap.py", f"{key}: {', '.join(v[key][:6])}", sev, "open", "B", "check, then fix or remove"))
        unw = pm["summary"]
    lc = OUT / "loadcost.json"
    if lc.exists():
        L = json.loads(read(lc))
        if L.get("pages_over_budget"):
            o = L["pages_over_budget"]
            out.append(("L-01", "loadcost.py", f"{len(o)} (page, role) pairs spend more than 200 ms of database time at 250x; worst: " + "; ".join(f"{x['page']}/{x['role']} {x['ms']} ms" for x in o[:5]), "high", "open", "B", "options/K-04-f09-case-rule.md"))
        if L.get("chatty"):
            out.append(("L-02", "loadcost.py", "pages that make 25+ backend requests per load: " + "; ".join(f"{x['page']}/{x['role']}={x['n']}" for x in L["chatty"][:6]) + " (each is a round trip to Singapore; some are batched by selectMany)", "medium", "open", "B", "batch into one RPC per page (needs a look at the page)"))
        for i, r in enumerate(L.get("top", [])[:5]):
            out.append((f"L-{i + 3:02d}", f"loadcost.py {r['page']}/{r['role']}", f"slow query at 250x: {r['db_ms']} ms {r['q'][:110]}" + (f" (seq scan {r['seq']})" if r.get("seq") else ""), "high" if r["db_ms"] > 1000 else "medium", "open", "B", "options/K-04-f09-case-rule.md"))
    l1 = OUT / "loadcost_1x.json"
    if l1.exists():
        bad = {}
        for r in json.loads(read(l1)):
            if r["code"] in (400, 404) and re.search(r"42703|42P01|42883|PGRST|does not exist", r.get("msg", "")):
                bad.setdefault((r["q"].split("?")[0], re.sub(r"\s+", " ", r["msg"])[60:140]), set()).add(r["page"])
        for i, ((q, m), pgs) in enumerate(sorted(bad.items())):
            out.append((f"Q-{i + 1:02d}", f"loadcost.py replay ({', '.join(sorted(pgs))})", f"the page's own query fails against the real schema: {q} -> {m.strip(chr(34) + '}')}. The call is optional, so the page loads but silently loses that data.", "high", "open", "A", "edit the query in the PHP (a one-word fix); not a migration"))
    st = OUT / "standards.json"
    if st.exists():
        for i, (sev, txt) in enumerate(json.loads(read(st))["violations"]):
            if sev == "info": continue
            kind = "untested" if "never named in" in txt else None
            cl = KIND.get(kind, ("B", "-"))
            out.append((f"T-{i + 1:02d}", "standards.py", txt, sev, "open", cl[0], cl[1]))
    for f in sorted(OUT.glob("smart_*x.json")):
        pass
    sg = OUT / "smart_growth.json"
    if sg.exists():
        g = [x for x in json.loads(read(sg)) if x["written"] and not x["deleted"] and (x["live_rows"] or 0) >= 1000]
        if g: out.append(("S-01", "smart.py", "tables that only grow (written, never deleted by a function or job), live rows: " + ", ".join(f"{x['table']}={x['live_rows']}" for x in g[:6]), "low", "open", "B", "options/B-dead-code.md (retention decision)"))
    out.append(("S-02", "live status_logs", "status_logs holds 22,910 rows of 'No tanod available for automatic dispatch' for 7 cases (Aug 27-Nov 18): 95% of the table, an append-only audit trail that cannot be pruned. The guard from 0139 stopped it; nothing similar caps other system remarks.", "low", "open", "B", "options/B-dead-code.md"))
    return out


def main():
    rs = rows()
    order = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}
    rs = sorted(rs, key=lambda r: (order.get(r[3], 9), r[0]))
    cnt = Counter(r[3] for r in rs if r[4] != "done"); cls = Counter(r[5] for r in rs if r[4] != "done")
    table = ["| id | source | gap | severity | status | class | fix / options |", "|---|---|---|---|---|---|---|"]
    for r in rs: table.append("| " + " | ".join(str(x).replace("|", "/").replace("\n", " ") for x in r) + " |")
    auto = f"{B}\n\n{len(rs)} rows. Severity: " + ", ".join(f"{k} {cnt.get(k, 0)}" for k in order) + ". Class: " + ", ".join(f"{k} {cls.get(k, 0)}" for k in "ABC") + ".\n\n" + "\n".join(table) + f"\n\n{E}"
    head = """# Gap ledger

One row per gap. **Class**: A = a script can generate the fix (see `tools/sweep/fix/`, output is a DRAFT migration + test, never applied);
B = needs one human decision, then scripted (options in `docs/sweep/options/`, no migration until Ace picks); C = changes the look, waits for Rose
(the front end sweep). Rows below the AUTO block are the team's; append business gaps there, one line each, same columns.

"""
    foot = """
## Business gaps (append here)

| id | source | gap | severity | status | class | fix / options |
|---|---|---|---|---|---|---|
"""
    old = read(LEDGER) if LEDGER.exists() else ""
    m = re.search(re.escape(E) + r"(.*)$", old, re.S)
    tail = m.group(1) if m and "Business gaps" in m.group(1) else foot
    LEDGER.parent.mkdir(parents=True, exist_ok=True)
    LEDGER.write_text(head + auto + tail, encoding="utf-8")
    save("ledger_counts.json", {"severity": dict(cnt), "class": dict(cls), "rows": len(rs)})
    print("LEDGER " + str(len(rs)) + " rows; severity " + ", ".join(f"{k}={cnt.get(k, 0)}" for k in order) + "; class " + ", ".join(f"{k}={cls.get(k, 0)}" for k in "ABC") + f" -> {LEDGER.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
